import os, html
S = os.path.dirname(os.path.abspath(__file__))   # user-guide/_src
ROOT = os.path.dirname(S)                          # user-guide (index.html, img/)
used = []

def fig(name, cap):
    p = f"img/{name}.jpg"
    assert os.path.exists(os.path.join(ROOT, p)), name
    used.append(p)
    return (f'<figure><img src="{p}" alt="{html.escape(cap)}" loading="lazy" width="520" height="1332">'
            f'<figcaption>{cap}</figcaption></figure>')

def shots(*items):
    return '<div class="shots">' + "".join(fig(n, c) for n, c in items) + "</div>"

def steps(*items):
    return '<ol class="steps">' + "".join(f"<li><span>{t}</span></li>" for t in items) + "</ol>"

def tip(t, kind="팁"):
    return f'<aside class="note"><b>{kind}</b><p>{t}</p></aside>'

def chapter(cid, title, when, body):
    return (f'<section class="chap" id="{cid}"><header><h2>{title}</h2>'
            f'<p class="when">{when}</p></header>{body}</section>')

C = []

def table(head, rows):
    h = "".join(f"<th>{x}</th>" for x in head)
    r = "".join("<tr>" + "".join(f"<td>{c}</td>" for c in row) + "</tr>" for row in rows)
    return f'<div class="tablewrap"><table><thead><tr>{h}</tr></thead><tbody>{r}</tbody></table></div>'

